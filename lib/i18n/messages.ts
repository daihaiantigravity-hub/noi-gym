export function getMessages(language: AppLanguage): Messages {
  return language === "vi" ? vietnamese : english;
}

export function translate(language: AppLanguage, key: MessageKey, values: Record<string, string | number> = {}) {
  return getMessages(language)[key].replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}

export function getIntlLocale(language: AppLanguage) {
  return language === "vi" ? "vi-VN" : "en-US";
}

export function formatDate(language: AppLanguage, value: string, options: Intl.DateTimeFormatOptions = {}) {
  return new Intl.DateTimeFormat(getIntlLocale(language), { day: "2-digit", month: "2-digit", year: "numeric", ...options }).format(new Date(value));
}

export function formatNumber(language: AppLanguage, value: number) {
  return new Intl.NumberFormat(getIntlLocale(language)).format(value);
}
