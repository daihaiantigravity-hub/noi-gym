export function getWorkspaceMessages(language: AppLanguage): WorkspaceMessages {
  return language === "vi" ? vietnamese : english;
}

export function workspaceText(language: AppLanguage, key: WorkspaceMessageKey, values: Record<string, string | number> = {}) {
  return getWorkspaceMessages(language)[key].replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}
